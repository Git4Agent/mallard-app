const MONTHS: Record<string, number> = { Jan: 1, Feb: 2, Mar: 3, Apr: 4, May: 5, Jun: 6, Jul: 7, Aug: 8, Sep: 9, Oct: 10, Nov: 11, Dec: 12 };
const DATE = "(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) (\\d{1,2}), (\\d{4})";
/** What `Intl.DateTimeFormat("zh-CN")` prints for the same instant. */
const zhDate = (month: string, day: string, year: string) => `${year}年${MONTHS[month]}月${day}日`;
const dates = (text: string) => text.replace(new RegExp(`${DATE}(?:,| at) (\\d{1,2}:\\d{2})`, "g"), (_m, mo, d, y, t) => `${zhDate(mo, d, y)} ${t}`)
  .replace(new RegExp(DATE, "g"), (_m, mo, d, y) => zhDate(mo, d, y));
/** `Intl.NumberFormat("zh-CN", { notation: "compact" })`: Chinese counts in 万, not K. */
const wan = (k: string) => `${(Number(k) / 10).toFixed(1).replace(/\.0$/, "")}万`;

/* The chip's label joins its word and line: each half translates on its own. */
function cloudWord(word: string): string {
  const words: Record<string, string> = { Private: "私有", Draft: "草稿", "In review": "审核中", "Sign in": "登录", "Not pushed": "未上传", "Checking…": "正在检查…", "Being deleted": "正在删除", Gone: "已不存在", "No access": "无权访问", "Can't check": "无法检查", Rejected: "已拒绝" };
  return words[word] ?? word.replace(/^Public v(\d+)$/, "公开 v$1");
}
function cloudLine(line: string): string {
  return line
    .replace(/^The draft is (\d+) push(?:es)? past version (\d+)\.$/, "草稿比 Version $2 多 $1 次上传。")
    .replace(/^(\d+) push(?:es)? past version (\d+), which is public\.$/, "比 Version $2 多 $1 次上传，Version $2 已公开。")
    .replace(/^Version (\d+) is public\. The draft is the same\.$/, "Version $1 已公开，草稿与之相同。")
    .replace(/^The draft is waiting for a Mallard Cloud admin\.$/, "草稿正在等待 Mallard Cloud 管理员审核。")
    .replace(/^Signed out of Mallard Cloud\.$/, "已退出 Mallard Cloud。")
    .replace(/^Nothing pushed yet\.$/, "尚未上传任何内容。")
    .replace(/^Push creates it again\.$/, "上传会重新创建它。")
    .replace(/^Deleted, or this account lost access\. Push creates it again\.$/, "已删除，或此账户已失去访问权限。上传会重新创建它。")
    .replace(/^Mallard Cloud refused this account\. It may be suspended\.$/, "Mallard Cloud 拒绝了此账户，可能已被停用。");
}

