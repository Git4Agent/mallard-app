/* "1 skill changed on both sides, 1 skill can't be synced": each part on its own. */
function libraryParts(text: string): string {
  return text.split(", ").map((part) => part
    .replace(/^(\d+) skills? changed on both sides$/, "$1 个 Skill 两边都有更改")
    .replace(/^(\d+) skills? can't be synced$/, "$1 个 Skill 无法同步")).join("，");
}
/* A Pull row's chosen action, as the choice list words it. */
function translateLibraryAction(label: string): string {
  return label
    .replace(/^Keep local as (.+) and overwrite$/, "将本地保留为 $1 并覆盖")
    .replace(/^Overwrite local content$/, "覆盖本地内容")
    .replace(/^Install stored content$/, "安装存储中的内容")
    .replace(/^Update from storage$/, "从存储更新");
}


